function createPostRegistrySource(posts, options = {}) {
  const publicOnly = options.publishedOnly === true;
  const includedPosts = posts
    .filter(post => !publicOnly || post.status === "published")
    .sort((left, right) => {
      const leftKey = `${left.year}/${left.slug}`;
      const rightKey = `${right.year}/${right.slug}`;
      return leftKey.localeCompare(rightKey);
    });

  const imports = includedPosts.map((post, index) => {
    const identifier = `Article${String(index + 1).padStart(3, "0")}`;
    return {
      identifier,
      line: `import ${identifier} from "./${post.year}/${post.slug}/article.mdx";`,
      key: `${post.year}/${post.slug}`,
    };
  });

  const importLines = imports.map(entry => entry.line).join("\n");
  const registryLines = imports
    .map(entry => `  "${entry.key}": ${entry.identifier},`)
    .join("\n");

  return `// This file is generated by pnpm sync:posts. Do not edit manually.\nimport type { ComponentType } from "react";\n${
    importLines ? `\n${importLines}\n` : ""
  }\ntype ArticleComponent = ComponentType;\n\nconst articleComponents: Record<string, ArticleComponent> = {\n${registryLines}\n};\n\nexport function getArticleComponent(year: string, slug: string) {\n  return articleComponents[\`${"${year}/${slug}"}\`];\n}\n`;
}

module.exports = {
  createPostRegistrySource,
};
